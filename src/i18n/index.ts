const savedLocale = localStorage.getItem('operix_locale') as 'fr' | 'en' | null

export const i18n = createI18n({
  legacy: false,
  locale: savedLocale ?? 'fr',
  fallbackLocale: 'fr',
  messages,
})

export function setLocale(locale: 'fr' | 'en') {
  i18n.global.locale.value = locale
  localStorage.setItem('operix_locale', locale)
  document.documentElement.lang = locale
}

export function getLocale(): 'fr' | 'en' {
  return i18n.global.locale.value as 'fr' | 'en'
}
